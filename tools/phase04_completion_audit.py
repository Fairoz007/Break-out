"""Phase 04 completion audit (master prompt §21/§23).

Audits docs/phase04/requirements.json: missing requirements (canonical dialogue/shot/mission/objective coverage),
missing implementation paths, missing tests, missing evidence, failed, blocked, unfinished missions, missing dialogue,
missing cinematics, missing character animations, untested Windows build and self-verification. Writes
docs/phase04/COMPLETION_AUDIT.md and exits 1 while any mandatory requirement is not independently VERIFIED.

    python -I tools/phase04_completion_audit.py
"""
import json, sys
from collections import Counter
from pathlib import Path

R = Path(__file__).resolve().parents[1]
D = R / "docs/phase04"
reg = json.loads((D / "requirements.json").read_text(encoding="utf-8"))
reqs = reg["requirements"]
ids = {r["id"] for r in reqs}
vfile = D / "qa_verdicts.json"
verdicts = {v["id"]: v for v in json.loads(vfile.read_text(encoding="utf-8"))["verdicts"]} if vfile.exists() else {}

lines = [l["id"] for l in json.loads((R / "data/ch01/dialogue.json").read_text(encoding="utf-8"))["lines"]]
shots = [s["id"] for s in json.loads((R / "data/ch01/shots.json").read_text(encoding="utf-8"))["shots"]]
missions = json.loads((R / "data/ch01/missions.json").read_text(encoding="utf-8"))["missions"]
objectives = [o["id"] for m in missions for o in m["objectives"]]
missing_req = [f"dialogue {l}" for l in lines if f"P04-C-P03-DLG-{l}" not in ids] + [f"shot {s}" for s in shots if f"P04-C-P03-SHOT-{s}" not in ids] \
    + [f"objective {o}" for o in objectives if f"P04-C-P03-OBJ-{o}" not in ids] + [f"mission {i}" for i in range(1, 7) if f"P04-MIS-0{i}-012" not in ids]

st = Counter(r["status"] for r in reqs)
mand = [r for r in reqs if r.get("mandatory")]
unverified = [r for r in mand if r["status"] != "VERIFIED"]
missing_paths = [r["id"] for r in reqs if not r.get("implementation_paths") and not r["id"].startswith("P04-BASE")]
missing_tests = [r["id"] for r in reqs if not r.get("test_method")]
missing_evidence = [r["id"] for r in reqs if r["status"] in ("IMPLEMENTED_UNTESTED", "VERIFIED", "FAILED") and not r.get("evidence")]
failed = [r["id"] for r in reqs if r["status"] == "FAILED"]
blocked = [r["id"] for r in reqs if r["status"] == "BLOCKED"]
self_verified = [r["id"] for r in reqs if r["status"] == "VERIFIED" and (r["id"] not in verdicts or verdicts[r["id"]].get("reviewer") == r["owner"])]
unfinished_missions = [r["id"] for r in reqs if r["id"].startswith("P04-MIS-") and r["id"].endswith("-012") and r["status"] != "VERIFIED"]
missing_dialogue = [r["id"] for r in reqs if r["id"].startswith("P04-C-P03-DLG-") and r["status"] != "VERIFIED"]
missing_cine = [r["id"] for r in reqs if (r["id"].startswith("P04-C-P03-SHOT-") or r["id"].startswith("P04-CIN-")) and r["status"] != "VERIFIED"]
missing_anim = [r["id"] for r in reqs if r["id"].startswith("P04-ANIM-") and r["status"] != "VERIFIED"]
build = [r for r in reqs if r["id"].startswith("P04-BUILD-")]
windows_untested = any(r["status"] != "VERIFIED" for r in build)


def p(e):
    q = e.split("#")[0].strip()
    return q if "/" in q and " " not in q and q.split("/")[0] in ("tests", "docs", "assets", "scripts", "tools", "build") else None


dangling = sorted({(r["id"], p(e)) for r in reqs for e in r.get("evidence", []) if p(e) and not (R / p(e)).exists()})
gate = "COMPLETE" if not (unverified or missing_req or dangling or self_verified or windows_untested or failed) else "INCOMPLETE"

md = ["# Phase 04 completion audit", "", f"Generated by `tools/phase04_completion_audit.py`. **PHASE 04 — {gate}.**", "",
      "Registry bookkeeping plus evidence-path existence; not a substitute for runtime or visual testing.", "",
      "| Measure | Count |", "|---|---|", f"| Total requirements | {len(reqs)} |", f"| Mandatory | {len(mand)} |"]
md += [f"| {s} | {st.get(s, 0)} |" for s in reg["statuses"]]
md += [f"| Mandatory not VERIFIED | {len(unverified)} |", f"| Missing requirements (canonical coverage) | {len(missing_req)} |",
       f"| Missing implementation paths | {len(missing_paths)} |", f"| Missing test methods | {len(missing_tests)} |",
       f"| Status without evidence | {len(missing_evidence)} |", f"| Evidence paths missing on disk | {len(dangling)} |",
       f"| FAILED | {len(failed)} |", f"| BLOCKED | {len(blocked)} |", f"| VERIFIED without independent verdict | {len(self_verified)} |",
       f"| Missions not VERIFIED | {len(unfinished_missions)} of 6 |", f"| Dialogue lines not VERIFIED | {len(missing_dialogue)} of {len(lines)} |",
       f"| Cinematic rows not VERIFIED | {len(missing_cine)} |", f"| Character animation rows not VERIFIED | {len(missing_anim)} |",
       f"| Windows build runtime-verified | {'no' if windows_untested else 'yes'} |", ""]
for title, items in [("Missing requirements", missing_req), ("FAILED", failed), ("BLOCKED", blocked), ("Evidence missing on disk", [f"{a}: {b}" for a, b in dangling]),
                     ("VERIFIED without independent verdict", self_verified), ("Unfinished missions", unfinished_missions), ("Animation rows not VERIFIED", missing_anim)]:
    if items:
        md += [f"## {title}", ""] + [f"- {x}" for x in items[:150]] + ([f"- … {len(items) - 150} more"] if len(items) > 150 else []) + [""]
(D / "COMPLETION_AUDIT.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print(json.dumps({"gate": gate, "total": len(reqs), "status": dict(st), "mandatory_unverified": len(unverified), "missing_req": len(missing_req),
                  "failed": len(failed), "blocked": len(blocked), "dangling": len(dangling), "self_verified": len(self_verified),
                  "missions_unverified": len(unfinished_missions), "windows_untested": windows_untested}))
sys.exit(0 if gate == "COMPLETE" else 1)
