"""Phase 03 completion audit (master prompt section 19).

Reads docs/phase03/requirements.json (+ qa_verdicts.json) and reports totals, verified / failed / blocked counts,
missing tests, missing evidence, missing assets, unfinished missions, unverified cinematics and the Windows build
state. Writes docs/phase03/COMPLETION_AUDIT.md. Exits 1 while any mandatory requirement is not VERIFIED, any
evidence path is missing on disk, or a VERIFIED row lacks an independent verdict. Bookkeeping only: it never
substitutes for runtime or visual testing.

    python -I tools/phase03_completion_audit.py
"""
import json, sys
from collections import Counter
from pathlib import Path

R = Path(__file__).resolve().parents[1]
D = R / "docs/phase03"
reg = json.loads((D / "requirements.json").read_text(encoding="utf-8"))
reqs = reg["requirements"]
verdicts = {v["id"]: v for v in json.loads((D / "qa_verdicts.json").read_text(encoding="utf-8"))["verdicts"]} if (D / "qa_verdicts.json").exists() else {}

st = Counter(r["status"] for r in reqs)
mand = [r for r in reqs if r.get("mandatory")]
unverified = [r for r in mand if r["status"] != "VERIFIED"]
missing_tests = [r["id"] for r in reqs if not r.get("test_procedure")]
missing_evidence = [r["id"] for r in reqs if r["status"] in ("IMPLEMENTED_UNTESTED", "VERIFIED", "FAILED") and not r.get("evidence")]


def path_part(e):
    p = e.split("#")[0].strip()
    return p if ("/" in p and not p.startswith("http") and " " not in p and p.split("/")[0] in ("tests", "docs", "assets", "scripts", "tools", "build", "asset_library")) else None


dangling = sorted({(r["id"], path_part(e)) for r in reqs for e in r.get("evidence", []) if path_part(e) and not (R / path_part(e)).exists()})
missing_files = sorted({(r["id"], f) for r in reqs for f in r.get("implementation_files", []) if not (R / f).exists()})
self_verified = [r["id"] for r in reqs if r["status"] == "VERIFIED" and (r["id"] not in verdicts or verdicts[r["id"]].get("reviewer") == r["owner"])]

# Required runtime assets referenced by the environment builders
asset_refs = set()
for gd in (R / "scripts").rglob("*.gd"):
    for tok in gd.read_text(encoding="utf-8", errors="replace").split('"'):
        if tok.startswith("res://assets/") and "%" not in tok and tok.endswith((".glb", ".gltf", ".tres", ".jpg", ".png", ".wav", ".ogg")):
            asset_refs.add(tok)
missing_assets = sorted(a for a in asset_refs if not (R / a[6:]).exists())

missions = [r for r in reqs if r["id"].startswith("P03-MIS-") and r["id"].endswith("-000")]
unfinished_missions = [r["id"] for r in missions if r["status"] != "VERIFIED"]
cine = [r for r in reqs if r["id"].startswith(("P03-SHOT-", "P03-CIN-"))]
unverified_cine = [r["id"] for r in cine if r["status"] != "VERIFIED"]
build = [r for r in reqs if r["id"] in ("P03-QA-010", "P03-QA-011")]
windows_untested = any(r["status"] != "VERIFIED" for r in build)
exe = R / "build/windows/BreakoutNoWayBack.exe"

gate = "COMPLETE" if not (unverified or dangling or missing_files or self_verified or missing_assets or windows_untested) else "INCOMPLETE"
md = ["# Phase 03 completion audit", "", f"Generated by `tools/phase03_completion_audit.py`. **PHASE 03 — {gate}.**", "",
      "Counts registry records and checks evidence paths on disk. It is not a substitute for runtime or visual testing.", "",
      "| Measure | Count |", "|---|---|", f"| Total requirements | {len(reqs)} |", f"| Mandatory | {len(mand)} |"]
md += [f"| {s} | {st.get(s, 0)} |" for s in reg["statuses"]]
md += [f"| Mandatory not VERIFIED | {len(unverified)} |", f"| Missing test procedures | {len(missing_tests)} |",
       f"| Status claims without evidence | {len(missing_evidence)} |", f"| Evidence paths missing on disk | {len(dangling)} |",
       f"| Implementation files missing | {len(missing_files)} |", f"| VERIFIED without independent verdict | {len(self_verified)} |",
       f"| Runtime asset references missing | {len(missing_assets)} of {len(asset_refs)} |",
       f"| Missions not VERIFIED | {len(unfinished_missions)} of {len(missions)} |", f"| Cinematic rows not VERIFIED | {len(unverified_cine)} of {len(cine)} |",
       f"| Windows build tested and verified | {'no' if windows_untested else 'yes'} (executable {'present' if exe.exists() else 'absent'}) |", ""]
for title, items in [("Evidence paths missing on disk", [f"{a}: {b}" for a, b in dangling]), ("Implementation files missing", [f"{a}: {b}" for a, b in missing_files]),
                     ("VERIFIED without independent verdict", self_verified), ("Runtime asset references missing", missing_assets),
                     ("Status claims without evidence", missing_evidence), ("Unfinished missions", unfinished_missions)]:
    if items:
        md += [f"## {title}", ""] + [f"- {x}" for x in items[:200]] + ([f"- … {len(items) - 200} more"] if len(items) > 200 else []) + [""]
md += ["## Mandatory requirements not yet VERIFIED", "", "| ID | Status | Requirement |", "|---|---|---|"]
md += [f"| {r['id']} | {r['status']} | {r['requirement'][:90]} |" for r in unverified]
(D / "COMPLETION_AUDIT.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print(json.dumps({"gate": gate, "total": len(reqs), "status": dict(st), "mandatory_unverified": len(unverified), "missing_tests": len(missing_tests),
                  "missing_evidence": len(missing_evidence), "dangling_evidence": len(dangling), "missing_impl_files": len(missing_files),
                  "self_verified": len(self_verified), "missing_assets": len(missing_assets), "missions_unverified": len(unfinished_missions),
                  "cinematics_unverified": len(unverified_cine), "windows_untested": windows_untested}))
sys.exit(0 if gate == "COMPLETE" else 1)
