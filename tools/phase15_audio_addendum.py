"""QAF-21: automated audit of the 27 DISC15 discovery audio clips added after AUDIO_MATERIALS_AUDIT.md was generated.
Checks file presence, SHA256 against assets.json, FFmpeg decode, duration, peak/RMS/full-scale samples, licence evidence
and Godot load evidence. Listening is NOT performed. Writes asset_library/manifests/phase15/audio_discovery_addendum.json
and replaces the addendum section at the end of docs/qa/AUDIO_MATERIALS_AUDIT.md.
python -I tools/phase15_audio_addendum.py
"""
import hashlib, json, subprocess, sys
from array import array
from pathlib import Path

R = Path(__file__).resolve().parents[1]
A = json.loads((R / 'asset_library/manifests/assets.json').read_text(encoding='utf-8'))
G = {g['asset_id']: g for g in json.loads((R / 'asset_library/manifests/phase15/godot_validation.json').read_text(encoding='utf-8'))}
clips = [a for a in A if a['asset_id'].startswith('DISC15') and a['category'] == 'audio']
rows, fails = [], 0
for a in clips:
    f = R / a['runtime_file']; r = dict(asset_id=a['asset_id'], file=a['runtime_file'], bundles=a.get('requirement_bundle'), scenes=a.get('required_by_scene'))
    r['present'] = f.is_file()
    r['sha_match'] = r['present'] and hashlib.sha256(f.read_bytes()).hexdigest() == a['runtime_checksum']
    lic = a.get('license_record') or a.get('license_file')
    r['license'] = a['license']; r['license_evidence'] = bool(lic) and (R / lic).is_file()
    pr = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration:stream=sample_rate,channels,codec_name', '-of', 'json', str(f)], capture_output=True, text=True)
    info = json.loads(pr.stdout or '{}'); st = (info.get('streams') or [{}])[0]
    r['codec'], r['sample_rate'], r['channels'] = st.get('codec_name'), st.get('sample_rate'), st.get('channels')
    r['duration_s'] = round(float(info.get('format', {}).get('duration', 0)), 2)
    dec = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(f), '-f', 's16le', '-ac', '1', '-'], capture_output=True)
    r['decode_ok'] = dec.returncode == 0 and not dec.stderr.strip() and len(dec.stdout) > 0
    s = array('h', dec.stdout[:len(dec.stdout) // 2 * 2])
    peak = max((abs(x) for x in s), default=0)
    r['peak'] = round(peak / 32768, 3); r['full_scale_samples'] = sum(1 for x in s if abs(x) >= 32767)
    r['rms'] = round((sum(x * x for x in s) / max(len(s), 1)) ** 0.5 / 32768, 4); r['silent'] = r['rms'] < 0.001
    g = G.get(a['asset_id']); r['godot_load'] = g.get('load') if g else 'NO EVIDENCE'
    r['pass'] = all([r['present'], r['sha_match'], r['license_evidence'], r['decode_ok'], not r['silent'], r['godot_load'] == 'VERIFIED'])
    r['flags'] = [w for w, c in [('full-scale samples in mono mixdown', r['full_scale_samples'] > 0), ('peak >= 0.99', r['peak'] >= 0.99)] if c]
    fails += not r['pass']; rows.append(r)
(R / 'asset_library/manifests/phase15/audio_discovery_addendum.json').write_text(json.dumps(rows, indent=2), encoding='utf-8')

md = ['## Addendum: DISC15 discovery clips (QAF-21)', '',
      f'Audits the {len(rows)} DISC15 audio clips added after the main audit above. Generated by `tools/phase15_audio_addendum.py`; data in [audio_discovery_addendum.json](../../asset_library/manifests/phase15/audio_discovery_addendum.json).', '',
      f'**Automated checks: {len(rows) - fails}/{len(rows)} pass** (file present, SHA256 matches assets.json, licence evidence on disk, FFmpeg decodes with no errors, not silent, Godot load VERIFIED). **Listening was NOT performed**, so realism, loop seams and mix suitability are still NOT TESTED.', '',
      'Effect on the Missing table above: crowd audio and coastal wind/waves now have downloaded candidates (rows below), so those rows move from MISSING to *candidate, not auditioned*. VO, PA speech, radio speech, bus engine and score are still missing (blocker P06). The Phase 01 `AUDIO_FOLEY` record now reads PARTIALLY_VERIFIED (decoded waveform pass, listening not tested), which supersedes serious issue 6 above.', '',
      '| Asset | Bundle | Format | Duration | Peak | Full-scale | Godot | Result | Flags |', '|---|---|---|---|---|---|---|---|---|']
for r in rows:
    md.append(f"| `{r['asset_id']}` | {', '.join(r['bundles'] or [])} | {r['codec']} {r['sample_rate']} Hz {r['channels']} ch | {r['duration_s']} s | {r['peak']} | {r['full_scale_samples']} | {r['godot_load']} | {'PASS' if r['pass'] else 'FAIL'} | {'; '.join(r['flags']) or '—'} |")
doc = R / 'docs/qa/AUDIO_MATERIALS_AUDIT.md'; text = doc.read_text(encoding='utf-8')
text = text.split('\n## Addendum: DISC15 discovery clips (QAF-21)')[0].rstrip('\n')
doc.write_text(text + '\n\n' + '\n'.join(md) + '\n', encoding='utf-8')
print(f'{len(rows)} clips, {fails} failing')
sys.exit(bool(fails))
