holes=0
def box(dims, loc, material, *args, **kwargs):
    global holes
    if tuple(dims)==(0.004,0.022,0.022): return None
    if tuple(dims)!=(0.035,1.80,1.05): return original(dims,loc,material,*args,**kwargs)
    # 36 x 21 cells, 24 mm diameter round punched openings, 3 mm sheet.
    # Each cell is an eight-sided square annulus with real cylindrical inside walls.
    vertices=[]; faces=[]
    n=12
    for iy in range(36):
        for iz in range(21):
            cy=-.875+iy*.05;cz=2.9+iz*.05
            base=len(vertices)
            for x,radial in [(2.7185,False),(2.7185,True),(2.7215,False),(2.7215,True)]:
                for k in range(n):
                    a=2*math.pi*k/n
                    co,si=math.cos(a),math.sin(a)
                    r=.012 if radial else .025/max(abs(co),abs(si))
                    vertices.append((x,cy+co*r,cz+si*r))
            for k in range(n):
                j=(k+1)%n
                faces.extend([(base+k,base+j,base+n+j,base+n+k),
                              (base+2*n+j,base+2*n+k,base+3*n+k,base+3*n+j),
                              (base+n+k,base+n+j,base+3*n+j,base+3*n+k)])
            holes+=1
    mesh=bpy.data.meshes.new('True punched steel holes');mesh.from_pydata(vertices,[],faces);mesh.update()
    ob=bpy.data.objects.new('Backboard 756 real through holes',mesh);bpy.context.collection.objects.link(ob)
    p._finish(ob,material,0,0)
    return ob
p.box=box
