"""Phase 02 completion audit (protocol section 11). Reads docs/PHASE_02_REQUIREMENTS.json and reports totals,
statuses, missing implementation references, missing tests, missing evidence and missing scene / dialogue /
camera-shot mappings against the canonical data. Writes docs/qa/PHASE_02_COMPLETION_AUDIT.md.
Exits 1 while any mandatory requirement is not VERIFIED. This is bookkeeping, not a substitute for runtime or
visual testing.
python -I tools/phase02_completion_audit.py
"""
import json, sys
from collections import Counter
from pathlib import Path

R = Path(__file__).resolve().parents[1]
reg = json.loads((R / 'docs/PHASE_02_REQUIREMENTS.json').read_text(encoding='utf-8'))
reqs = reg['requirements']
lines = [l['id'] for l in json.loads((R / 'data/ch01/dialogue.json').read_text(encoding='utf-8'))['lines']]
shots = [s['id'] for s in json.loads((R / 'data/ch01/shots.json').read_text(encoding='utf-8'))['shots']]
scenes = [f'CH01_M0{i}_SC01' for i in range(1, 7)]
st = Counter(r['status'] for r in reqs)
mand = [r for r in reqs if r.get('mandatory')]
missing_impl = [r['id'] for r in reqs if not r['implementation_files'] and r['status'] != 'BLOCKED']
missing_files = [(r['id'], f) for r in reqs for f in r['implementation_files'] if not (R / f).exists()]
missing_tests = [r['id'] for r in reqs if not r.get('test_method')]
missing_evidence = [r['id'] for r in reqs if r['status'] not in ('NOT_STARTED', 'BLOCKED') and not r.get('evidence')]
dlg_mapped = {r.get('dialogue_id') for r in reqs}
shot_mapped = {r.get('shot_id') for r in reqs}
scene_mapped = {r.get('scene_id') for r in reqs}
miss_dlg = [l for l in lines if l not in dlg_mapped]
miss_shot = [s for s in shots if s not in shot_mapped]
miss_scene = [s for s in scenes if s not in scene_mapped]
unverified = [r for r in mand if r['status'] != 'VERIFIED']
gate = 'COMPLETE' if not unverified and not (miss_dlg or miss_shot or miss_scene) else 'INCOMPLETE'

md = ['# Phase 02 completion audit', '', f'Generated by `tools/phase02_completion_audit.py`. **PHASE 02 — {gate}.**', '',
      'This audit counts registry records. It does not replace runtime or visual testing.', '',
      '| Measure | Count |', '|---|---|', f'| Total requirements | {len(reqs)} |', f'| Mandatory (P0/P1) | {len(mand)} |']
md += [f'| {s} | {st.get(s, 0)} |' for s in reg['statuses']]
md += [f'| Mandatory not VERIFIED | {len(unverified)} |', f'| Missing implementation references | {len(missing_impl)} |',
       f'| Implementation files that do not exist | {len(missing_files)} |', f'| Missing test methods | {len(missing_tests)} |',
       f'| Implemented but no evidence | {len(missing_evidence)} |', f'| Unmapped scenes | {len(miss_scene)} of {len(scenes)} |',
       f'| Unmapped dialogue lines | {len(miss_dlg)} of {len(lines)} |', f'| Unmapped camera shots | {len(miss_shot)} of {len(shots)} |', '']
for title, items in [('Missing implementation references', missing_impl), ('Implementation files that do not exist', [f'{a}: {b}' for a, b in missing_files]),
                     ('Implemented but no evidence', missing_evidence), ('Unmapped dialogue', miss_dlg), ('Unmapped shots', miss_shot), ('Unmapped scenes', miss_scene)]:
    if items:
        md += [f'## {title}', ''] + [f'- {x}' for x in items] + ['']
md += ['## Mandatory requirements not yet VERIFIED', '', '| ID | Status | Blocking / pending |', '|---|---|---|']
for r in unverified:
    why = '; '.join(r.get('blocking_issues', []) + r.get('pending_checks', [])) or '—'
    md.append(f'| {r["id"]} | {r["status"]} | {why} |')
(R / 'docs/qa/PHASE_02_COMPLETION_AUDIT.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
print(json.dumps({'gate': gate, 'total': len(reqs), 'status': dict(st), 'mandatory_unverified': len(unverified),
                  'missing_impl': len(missing_impl), 'missing_files': len(missing_files), 'missing_evidence': len(missing_evidence),
                  'unmapped': [len(miss_scene), len(miss_dlg), len(miss_shot)]}))
sys.exit(0 if gate == 'COMPLETE' else 1)
